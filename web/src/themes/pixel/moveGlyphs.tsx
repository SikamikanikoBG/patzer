function bitmap(rows: readonly string[]): ReactNode {
  return (
    <svg width="24" height="24" viewBox="0 0 12 12" shapeRendering="crispEdges">
      {spriteRuns(rows).filter((run) => run.pixel === '#').map((run) => (
        <rect key={`${run.x},${run.y}`} x={run.x} y={run.y} width={run.width} height="1" fill="currentColor" />
      ))}
    </svg>
  );
}

export const PIXEL_MOVE_GLYPHS = Object.fromEntries(
  Object.entries(GLYPH_BITMAPS).map(([kind, rows]) => [kind, bitmap(rows)]),
) as Record<GlyphKind, ReactNode>;
